#!/usr/bin/env node
// GhostFleet node-agent acceptance control plane (local, disposable-only).
//
// This file is an ACCEPTANCE HARNESS, not a second implementation of the node
// plane. Every protocol decision (body caps, credential digest, lifecycle
// admission, clock skew, nonce replay, rate limit, task queue, result
// idempotency, projections) is made by the real modules under
// src/control-plane/. This file only:
//   1. loads those modules and refuses to run when they are absent,
//   2. builds one node fixture through the real enrollment controller
//      (create -> prepare -> claim -> materialize) and binds a credential with
//      the real mintNodeCredential() + the real store,
//   3. serves them over node:https with a certificate generated by the shell,
//   4. adds an operator surface (create task / read node / read timeline), a
//      read-only observer surface for an independent consumer, and a request
//      journal so the shell can compare real wire payloads,
//   5. offers CLI subcommands the shell drives (create-task, node, tasks,
//      observe, host-report, health).
//
// Anything that looks like a protocol rule implemented here would be a defect:
// the acceptance run must fail rather than accept a harness-only behaviour.
//
// Usage (serve):
//   node scripts/node-agent-acceptance-control-plane.mjs serve \
//     --work <dir> --cert <pem> --key <pem> [--host 127.0.0.1] [--port 0] \
//     [--node-id acceptance-node] [--agent-version 0.0.0]
// Usage (client, one subcommand per call):
//   node scripts/node-agent-acceptance-control-plane.mjs create-task \
//     --base-url https://127.0.0.1:PORT --ca <ca.pem> \
//     --operator-token-file <file> --operation node.observe --params '{}'
//   node ... node   --base-url ... --ca ... --operator-token-file <file>
//   node ... tasks  --base-url ... --ca ... --operator-token-file <file>
//   node ... observe --base-url ... --ca ... --observer-token-file <file> [--json]
//   node ... host-report --base-url ... --ca ... --operator-token-file <file> ...
//   node ... health --base-url ... --ca ...

import { createHash, randomBytes, timingSafeEqual } from "node:crypto";
import {
  appendFileSync,
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { createServer, request as httpsRequest } from "node:https";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = dirname(dirname(SCRIPT_PATH));

// Exported names this harness depends on. A missing module or a renamed export
// is an acceptance failure with an explicit code, never a skip.
const REQUIRED_MODULES = Object.freeze({
  "src/control-plane/node-agent.js": [
    "NODE_BODY_LIMITS",
    "AGENT_SCHEMA",
    "mintNodeCredential",
    "projectNode",
    "projectAgent",
    "sha256Hex",
  ],
  "src/control-plane/store.js": ["InMemoryStore"],
  "src/control-plane/controller.js": ["GhostFleetController"],
  "src/control-plane/http.js": ["createHttpHandler", "BODY_LIMITS"],
});

const NODE_PLANE_PATHS = Object.freeze([
  /^\/v0\/nodes\/[^/]+\/heartbeat$/,
  /^\/v0\/nodes\/[^/]+\/tasks\/poll$/,
  /^\/v0\/nodes\/[^/]+\/tasks\/[^/]+\/result$/,
]);

const BODY_LOG_LIMIT = 32768;
const RESPONSE_LOG_LIMIT = 8192;

class AcceptanceError extends Error {
  constructor(code, message) {
    super(message);
    this.name = "AcceptanceError";
    this.code = code;
  }
}

function fail(code, message) {
  throw new AcceptanceError(code, message);
}

function isoNow() {
  return new Date().toISOString();
}

function parseArgv(argv) {
  const flags = new Map();
  const positional = [];
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith("--")) {
      positional.push(token);
      continue;
    }
    const eq = token.indexOf("=");
    if (eq !== -1) {
      flags.set(token.slice(2, eq), token.slice(eq + 1));
      continue;
    }
    const name = token.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith("--")) {
      flags.set(name, "true");
      continue;
    }
    flags.set(name, next);
    index += 1;
  }
  return { flags, positional };
}

function requiredFlag(flags, name) {
  const value = flags.get(name);
  if (typeof value !== "string" || value.length === 0 || value === "true") {
    fail("AC_MISSING_FLAG", "missing required--" + name);
  }
  return value;
}

function optionalFlag(flags, name, fallback = null) {
  const value = flags.get(name);
  if (value === undefined) return fallback;
  return value;
}

async function loadControlPlane() {
  const modules = {};
  for (const [relativePath, exports] of Object.entries(REQUIRED_MODULES)) {
    const absolute = join(REPO_ROOT, relativePath);
    if (!existsSync(absolute)) {
      fail(
        "AC_MISSING_MODULE",
        "node agent plane module is absent: " +
          absolute +
          " (produced by the control-plane node-agent implementation line; the acceptance run must not substitute a local protocol copy)",
      );
    }
    let loaded;
    try {
      loaded = await import(pathToFileURL(absolute).href);
    } catch (error) {
      fail("AC_MODULE_IMPORT_FAILED", relativePath + " failed to import: " + error.message);
    }
    const missing = exports.filter((name) => loaded[name] === undefined);
    if (missing.length > 0) {
      fail(
        "AC_MISSING_EXPORT",
        relativePath + " does not export: " + missing.join(", "),
      );
    }
    modules[relativePath] = loaded;
  }
  const nodeAgent = modules["src/control-plane/node-agent.js"];
  const httpModule = modules["src/control-plane/http.js"];
  for (const kind of ["heartbeat", "poll", "result"]) {
    if (!nodeAgent.NODE_BODY_LIMITS || !Number.isInteger(nodeAgent.NODE_BODY_LIMITS[kind])) {
      fail("AC_MISSING_EXPORT", "NODE_BODY_LIMITS." + kind + " is missing or not an integer");
    }
  }
  return {
    nodeAgent,
    store: modules["src/control-plane/store.js"],
    controller: modules["src/control-plane/controller.js"],
    http: httpModule,
  };
}

function sha256(value) {
  return createHash("sha256").update(value).digest();
}

function tokenEquals(left, right) {
  if (typeof left !== "string" || typeof right !== "string") return false;
  const a = sha256(left);
  const b = sha256(right);
  return timingSafeEqual(a, b);
}

function readTokenFile(path) {
  const raw = readFileSync(path, "utf8");
  return raw.trim();
}

// --- node fixture ---------------------------------------------------------
//
// The node is created by the real enrollment controller so the durable record,
// lifecycle and projections are the product's own. The credential is minted by
// the real mintNodeCredential(); only its digest enters durable state, and the
// token is written to a root-only file. No token ever reaches stdout or a log.
function buildNodeFixture(plane, options) {
  const store = new plane.store.InMemoryStore();
  const controller = new plane.controller.GhostFleetController({ store });
  const attempt = controller.createEnrollmentAttempt({
    asset_hint: "acceptance:node-agent-lifecycle",
    desired_state: "ACTIVE",
    ttl_seconds: 3600,
  });
  controller.prepareEnrollmentAttempt(attempt.attempt_id);
  controller.claimEnrollmentAttempt(attempt.attempt_id);
  controller.startMaterialization(attempt.attempt_id, {
    node_id: options.node_id,
    platform: "linux",
  });
  const node = store.getNode(options.node_uid_hint ?? attempt.node_uid) ?? null;
  const attemptAfter = controller.getEnrollmentAttempt(attempt.attempt_id);
  if (!attemptAfter.node_uid) fail("AC_FIXTURE_INVALID", "materialization did not bind a node_uid");
  const raw = store.getNode(attemptAfter.node_uid);
  if (!raw) fail("AC_FIXTURE_INVALID", "materialized node is absent from the store");
  const minted = plane.nodeAgent.mintNodeCredential();
  store.putNodeAgent(raw.node_uid, {
    ...(raw.agent ?? {}),
    credential_digest: minted.digestHex,
    credential_minted_at: new Date().toISOString(),
    agent_version: options.agent_version,
  });
  return {
    store,
    controller,
    node_uid: raw.node_uid,
    node_token: minted.token,
    enrollment_attempt_id: attempt.attempt_id,
  };
}

// --- file helpers ---------------------------------------------------------
function writeJsonFile(path, value, mode = 0o600) {
  writeFileSync(path, JSON.stringify(value, null, 2) + "\n", { mode });
  chmodSync(path, mode);
}

function appendJournal(path, entry) {
  appendFileSync(path, JSON.stringify(entry) + "\n");
}

function truncate(value, limit) {
  if (typeof value !== "string") return value;
  if (value.length <= limit) return value;
  return value.slice(0, limit) + "...<truncated " + String(value.length - limit) + " chars>";
}

function json(value, status = 200) {
  return new Response(JSON.stringify(value, null, 2) + "\n", {
    status,
    headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store" },
  });
}

// --- request bridge -------------------------------------------------------
// node:http gives Node streams, the product's handler speaks WHATWG Request /
// Response. The bridge is deliberately dumb: it copies the bytes and the
// headers, and it never inspects protocol semantics.
async function readRequestBuffer(request) {
  const chunks = [];
  let total = 0;
  for await (const chunk of request) {
    total += chunk.byteLength;
    // Guards the harness itself against an unbounded fixture upload. The
    // protocol cap is enforced by the product handler after this point.
    if (total > 1048576) fail("AC_REQUEST_TOO_LARGE", "harness bridge read more than 1 MiB");
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}

function toWebRequest(request, rawBody) {
  const headers = new Headers();
  for (const [key, value] of Object.entries(request.headers)) {
    if (value === undefined) continue;
    headers.set(key, Array.isArray(value) ? value.join(", ") : String(value));
  }
  const url = new URL(request.url ?? "/", "https://" + (request.headers.host ?? "127.0.0.1"));
  const method = (request.method ?? "GET").toUpperCase();
  const mayCarryBody = method !== "GET" && method !== "HEAD";
  return new Request(url, {
    method,
    headers,
    body: mayCarryBody && rawBody.length > 0 ? rawBody : undefined,
  });
}

function nodeUidFromPath(path) {
  const match = /^\/v0\/nodes\/([^/]+)\//.exec(path);
  return match ? decodeURIComponent(match[1]) : null;
}

function taskIdFromPath(path) {
  const match = /^\/v0\/nodes\/[^/]+\/tasks\/([^/]+)\/result$/.exec(path);
  return match ? decodeURIComponent(match[1]) : null;
}

// --- harness server -------------------------------------------------------
function createHarnessServer(plane, fixture, options) {
  // createHttpHandler takes the transport authorizer as an option: without it the
  // product refuses to serve ANY operator route (503
  // OPERATOR_AUTHORIZATION_UNAVAILABLE), which is its own fail-closed second line
  // behind productRoute() below. The adapter is the only component that knows the
  // operator bearer and the read-only consumer credential.
  const handleProductRequest = plane.http.createHttpHandler(fixture.controller, {
    authorizeOperator: (request) => adapterAuthorizeOperator(request),
  });
  const journalPath = join(options.work, "node-plane-requests.jsonl");
  const state = {
    node_uid: fixture.node_uid,
    agent_version: options.agent_version,
    node_id: options.node_id,
    started_at: options.started_at,
    requests: 0,
    heartbeats: 0,
    last_heartbeat_at: null,
    last_agent_sent_at: null,
    results: [],
    polls: 0,
    host: null,
    operator_token: options.operator_token,
    observer_token: options.observer_token,
    node_token: fixture.node_token,
  };

  function operatorAuthorized(request) {
    return tokenEquals(request.headers.get("x-ghostfleet-operator-token"), state.operator_token);
  }

  function observerAuthorized(request) {
    return tokenEquals(request.headers.get("x-ghostfleet-observer-token"), state.observer_token);
  }

  // The product handler (src/control-plane/http.js) deliberately carries no
  // transport authentication: the deployed adapter owns the operator bearer and
  // the read-only consumer credential. This process IS that adapter, so every
  // product route below is authorized here, before the product handler runs.
  function productRole(request) {
    if (operatorAuthorized(request)) return "operator";
    if (observerAuthorized(request)) return "observer";
    return null;
  }

  function isProductSurface(path) {
    return path === "/v0/node-tasks" || path === "/v0/nodes";
  }

  // The product's own operator gate. Allowed: null (the reference adapter's
  // success value) or true. A read-only consumer may only GET; anything else is
  // answered here with the same codes the shell asserts on.
  function adapterAuthorizeOperator(request) {
    const role = productRole(request);
    if (role === "operator") return null;
    if (role === "observer") {
      if (request.method.toUpperCase() === "GET") return null;
      return json({ ok: false, error: "OBSERVER_READ_ONLY" }, 403);
    }
    return json({ ok: false, error: "OPERATOR_AUTH_INVALID" }, 403);
  }

  async function productRoute(request, path) {
    const role = productRole(request);
    if (role === null) return json({ ok: false, error: "OPERATOR_AUTH_INVALID" }, 403);
    if (role === "observer" && request.method.toUpperCase() !== "GET") {
      // A consumer that can mint tasks is not an independent consumer.
      return json({ ok: false, error: "OBSERVER_READ_ONLY" }, 403);
    }
    const outcome = await handleProductRequest(request);
    const text = await outcome.text();
    // Fail closed if the product ever leaks a credential-ish field onto a
    // surface a read-only consumer can reach. The shell asserts this code
    // never appears in any response it reads.
    if (/credential/i.test(text)) {
      return json({ ok: false, error: "OBSERVER_PROJECTION_LEAK" }, 500);
    }
    return new Response(text, {
      status: outcome.status,
      headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store" },
    });
  }

  async function acceptanceRoute(request, path, rawBody) {
    const method = request.method.toUpperCase();
    if (method === "GET" && path === "/acceptance/health") {
      return json({
        ok: true,
        node_uid: state.node_uid,
        node_id: state.node_id,
        agent_version: state.agent_version,
        started_at: state.started_at,
        server_time: isoNow(),
        requests: state.requests,
        heartbeats: state.heartbeats,
        polls: state.polls,
        last_heartbeat_at: state.last_heartbeat_at,
        last_agent_sent_at: state.last_agent_sent_at,
        results: state.results.length,
        host: state.host,
      });
    }

    // Real product routes: operator task creation/listing and the node
    // projection, exactly as src/control-plane/http.js defines them. Nothing
    // here re-implements the protocol; the harness only adds the transport
    // authentication the deployed adapter would add.
    if (isProductSurface(path)) return await productRoute(request, path);

    return json({ ok: false, error: "NOT_FOUND" }, 404);
  }

  async function handler(request, response) {
    const startedAt = Date.now();
    const path = (new URL(request.url ?? "/", "https://127.0.0.1").pathname.replace(/\/+$/, "") || "/");
    state.requests += 1;
    let rawBody;
    let status = 500;
    let text = JSON.stringify({ ok: false, error: "HARNESS_INTERNAL" });
    let isNodePlane = NODE_PLANE_PATHS.some((pattern) => pattern.test(path));
    try {
      rawBody = await readRequestBuffer(request);
      const webRequest = toWebRequest(request, rawBody);
      // Product surfaces (/v0/node-tasks, /v0/nodes) must pass through the
      // adapter-level authorization in acceptanceRoute; sending them straight to
      // the product handler would bypass the operator/observer split entirely.
      const outcome = path.startsWith("/acceptance/") || isProductSurface(path)
        ? await acceptanceRoute(webRequest, path, rawBody)
        : await handleProductRequest(webRequest);
      status = outcome.status;
      text = await outcome.text();
      if (isNodePlane && status === 200) {
        let parsed = null;
        try {
          parsed = JSON.parse(text);
        } catch {
          parsed = null;
        }
        if (path.endsWith("/heartbeat")) {
          state.heartbeats += 1;
          state.last_heartbeat_at = parsed?.server_time ?? isoNow();
          try {
            const body = JSON.parse(rawBody.toString("utf8"));
            state.last_agent_sent_at = body?.sent_at ?? null;
          } catch {
            state.last_agent_sent_at = null;
          }
        } else if (path.endsWith("/tasks/poll")) {
          state.polls += 1;
        } else {
          state.results.push({
            task_id: taskIdFromPath(path),
            status: parsed?.task?.status ?? null,
            result_outcome: parsed?.task?.result_outcome ?? null,
            result_digest: parsed?.result_digest ?? null,
            idempotent: parsed?.idempotent ?? null,
            at: isoNow(),
          });
        }
      }
    } catch (error) {
      status = 500;
      text = JSON.stringify({ ok: false, error: error?.code ?? "HARNESS_INTERNAL", detail: error?.message ?? null }) + "\n";
    }
    response.writeHead(status, {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
    });
    response.end(text);
    // The journal is the harness's own wire record: it lets the shell compare
    // what the agent actually reported (result payloads) instead of trusting a
    // self-description. Tokens never enter it; authorization is redacted.
    appendJournal(journalPath, {
      at: isoNow(),
      method: request.method,
      path,
      status,
      duration_ms: Date.now() - startedAt,
      node_uid: nodeUidFromPath(path),
      body_bytes: rawBody ? rawBody.length : 0,
      body: isNodePlane && rawBody ? truncate(rawBody.toString("utf8"), BODY_LOG_LIMIT) : null,
      response: truncate(text, RESPONSE_LOG_LIMIT),
    });
  }

  return { handler, state, journalPath };
}

// --- serve ----------------------------------------------------------------
async function commandServe(argv) {
  const { flags } = parseArgv(argv);
  const work = requiredFlag(flags, "work");
  const certPath = requiredFlag(flags, "cert");
  const keyPath = requiredFlag(flags, "key");
  const host = optionalFlag(flags, "host", "127.0.0.1");
  const portFlag = optionalFlag(flags, "port", "0");
  const port = Number(portFlag);
  if (!Number.isInteger(port) || port < 0 || port > 65535) fail("AC_INVALID_FLAG", "--port must be an integer");
  const nodeId = optionalFlag(flags, "node-id", "acceptance-node");
  const agentVersion = optionalFlag(flags, "agent-version", process.env.GHOSTFLEET_AGENT_VERSION ?? "0.0.0");
  const startedAt = isoNow();

  mkdirSync(work, { recursive: true, mode: 0o700 });
  const plane = await loadControlPlane();
  const fixture = buildNodeFixture(plane, { node_id: nodeId, agent_version: agentVersion });

  const operatorToken = randomBytes(24).toString("hex");
  const observerToken = randomBytes(24).toString("hex");
  const operatorTokenPath = join(work, "operator-token");
  const observerTokenPath = join(work, "observer-token");
  const nodeTokenPath = join(work, "node-token");
  writeFileSync(operatorTokenPath, operatorToken + "\n", { mode: 0o600 });
  writeFileSync(observerTokenPath, observerToken + "\n", { mode: 0o600 });
  writeFileSync(nodeTokenPath, fixture.node_token + "\n", { mode: 0o600 });
  chmodSync(operatorTokenPath, 0o600);
  chmodSync(observerTokenPath, 0o600);
  chmodSync(nodeTokenPath, 0o600);

  const { handler, state } = createHarnessServer(plane, fixture, {
    work,
    node_id: nodeId,
    agent_version: agentVersion,
    started_at: startedAt,
    operator_token: operatorToken,
    observer_token: observerToken,
  });

  const server = createServer(
    { cert: readFileSync(certPath), key: readFileSync(keyPath) },
    (request, response) => {
      handler(request, response).catch((error) => {
        response.writeHead(500, { "content-type": "application/json" });
        response.end(JSON.stringify({ ok: false, error: "HARNESS_INTERNAL", detail: error?.message ?? null }));
      });
    },
  );

  await new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(port, host, resolve);
  });
  const address = server.address();
  const baseUrl = "https://" + host + ":" + String(address.port);

  const readyPath = join(work, "ready.json");
  writeJsonFile(readyPath, {
    ok: true,
    started_at: startedAt,
    tool: "node-agent-acceptance-control-plane.mjs",
    base_url: baseUrl,
    host,
    port: address.port,
    pid: process.pid,
    node_uid: fixture.node_uid,
    node_id: nodeId,
    enrollment_attempt_id: fixture.enrollment_attempt_id,
    agent_version: agentVersion,
    work,
    operator_token_file: operatorTokenPath,
    observer_token_file: observerTokenPath,
    node_token_file: nodeTokenPath,
    journal: join(work, "node-plane-requests.jsonl"),
    control_plane_modules: Object.keys(REQUIRED_MODULES),
    node_plane_paths: ["/v0/nodes/{node_uid}/heartbeat", "/v0/nodes/{node_uid}/tasks/poll", "/v0/nodes/{node_uid}/tasks/{task_id}/result"],
    schemas: { agent: plane.nodeAgent.AGENT_SCHEMA },
  }, 0o600);

  process.stdout.write(
    JSON.stringify({ ok: true, event: "ready", base_url: baseUrl, node_uid: fixture.node_uid, pid: process.pid }) + "\n",
  );

  const shutdown = (signal) => {
    process.stdout.write(JSON.stringify({ ok: true, event: "stopping", signal, heartbeats: state.heartbeats }) + "\n");
    server.close(() => process.exit(0));
    // A lingering keep-alive socket must not hold the job open forever.
    setTimeout(() => process.exit(0), 2000).unref();
  };
  process.on("SIGTERM", () => shutdown("SIGTERM"));
  process.on("SIGINT", () => shutdown("SIGINT"));
  process.on("exit", () => {});
  return new Promise(() => {});
}

// --- client ---------------------------------------------------------------
function clientCall(options, method, path, payload, tokenKind) {
  const url = new URL(path, options.baseUrl);
  const body = payload === undefined ? null : Buffer.from(JSON.stringify(payload));
  const headers = {};
  if (body) {
    headers["content-type"] = "application/json";
    headers["content-length"] = String(body.length);
  }
  if (tokenKind === "operator") headers["x-ghostfleet-operator-token"] = options.operatorToken;
  if (tokenKind === "observer") headers["x-ghostfleet-observer-token"] = options.observerToken;
  return new Promise((resolve, reject) => {
    const request = httpsRequest(
      {
        hostname: url.hostname,
        port: url.port,
        path: url.pathname + url.search,
        method,
        headers,
        ca: options.ca,
        servername: url.hostname,
      },
      (response) => {
        const chunks = [];
        response.on("data", (chunk) => chunks.push(chunk));
        response.on("end", () => resolve({ status: response.statusCode, text: Buffer.concat(chunks).toString("utf8") }));
      },
    );
    request.on("error", reject);
    if (body) request.write(body);
    request.end();
  });
}

function clientOptions(flags, { tokenKind }) {
  const baseUrl = requiredFlag(flags, "base-url");
  const caPath = requiredFlag(flags, "ca");
  const options = { baseUrl, ca: readFileSync(caPath) };
  if (tokenKind === "operator") options.operatorToken = readTokenFile(requiredFlag(flags, "operator-token-file"));
  if (tokenKind === "observer") options.observerToken = readTokenFile(requiredFlag(flags, "observer-token-file"));
  return options;
}

function emitClientResult(result, { pretty = true } = {}) {
  let text = result.text;
  try {
    const parsed = JSON.parse(result.text);
    text = pretty ? JSON.stringify(parsed, null, 2) : JSON.stringify(parsed);
  } catch {
    text = result.text.trimEnd();
  }
  process.stdout.write(text + "\n");
  process.stderr.write("HTTP " + String(result.status) + "\n");
  // 0 on success; 3 on an error response, so the shell can assert denials
  // without parsing the exit status of curl.
  process.exitCode = result.status >= 400 ? 3 : 0;
}

async function commandCreateTask(argv) {
  const { flags } = parseArgv(argv);
  const options = clientOptions(flags, { tokenKind: "operator" });
  const nodeUid = requiredFlag(flags, "node-uid");
  const operation = requiredFlag(flags, "operation");
  const paramsFlag = optionalFlag(flags, "params", "{}");
  let params;
  try {
    params = JSON.parse(paramsFlag);
  } catch {
    fail("AC_INVALID_FLAG", "--params must be JSON: " + paramsFlag);
  }
  // The product's own operator route: POST /v0/node-tasks.
  const payload = { node_uid: nodeUid, operation, params };
  const ttl = optionalFlag(flags, "ttl-seconds");
  if (ttl) payload.ttl_seconds = Number(ttl);
  emitClientResult(await clientCall(options, "POST", "/v0/node-tasks", payload, "operator"));
}

// Read the product node projection (GET /v0/nodes) and, when --node-uid is
// given, keep only that node. projectNode() is the product's own public shape:
// it carries agent.health / last_heartbeat_at / capability_digest and never a
// credential digest, nonce ring or token.
async function readNodeProjection(options, nodeUid) {
  const result = await clientCall(options, "GET", "/v0/nodes");
  let parsed;
  try {
    parsed = JSON.parse(result.text);
  } catch {
    fail("AC_INVALID_RESPONSE", "GET /v0/nodes did not return JSON");
  }
  if (result.status >= 400) return result;
  const nodes = Array.isArray(parsed.nodes) ? parsed.nodes : [];
  if (nodeUid === null) return { ...result, text: JSON.stringify({ ok: true, nodes }) };
  const node = nodes.find((entry) => entry?.node_uid === nodeUid);
  if (!node) return { ...result, status: 404, text: JSON.stringify({ ok: false, error: "NODE_NOT_FOUND", node_uid: nodeUid }) };
  return { ...result, text: JSON.stringify({ ok: true, node }) };
}

