async function commandRequestBody(argv) {
  const { flags } = parseArgv(argv);
  const kind = flags.get("kind");
  if (kind !== "heartbeat" && kind !== "result") fail("AC_INVALID_FLAG", "--kind must be heartbeat or result");
  const plane = await loadControlPlane();
  const template = protocolTemplate(plane);
  const body = envelopeBody(template, {
    node_uid: requiredFlag(flags, "node-uid"),
    agent_version: optionalFlag(flags, "agent-version", "0.0.0"),
    nonce: optionalFlag(flags, "nonce", randomBytes(24).toString("base64url")),
    boot_id: optionalFlag(flags, "boot-id", "acceptance-harness"),
    seq: Number(optionalFlag(flags, "seq", "1")),
    sent_at: optionalFlag(flags, "sent-at"),
  });
  if (!Number.isInteger(body.seq) || body.seq < 0) fail("AC_INVALID_FLAG", "--seq must be a non-negative integer");
  if (kind === "heartbeat") {
    body.health = template.health;
    body.capability_digest = template.capability_digest;
    body.queue_depth = 0;
    body.drift = [];
  } else {
    body.task_id = requiredFlag(flags, "task-id");
    const resultFlag = optionalFlag(flags, "result", null);
    if (resultFlag === null) {
      body.result = { outcome: "SUCCEEDED", observation: { source: "acceptance-harness", observed_at: isoNow() } };
    } else {
      try {
        body.result = JSON.parse(resultFlag);
      } catch {
        fail("AC_INVALID_FLAG", "--result must be JSON: " + resultFlag);
      }
    }
  }
  process.stdout.write(JSON.stringify(body, null, 2) + "\n");
}

