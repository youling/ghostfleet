#!/usr/bin/env python3
"""确定性构建 GhostFleet 节点 Agent 的 zipapp 载荷（合同 B/G）。

用法（仓库根或包目录均可）：

    python3 packages/node-agent/tools/build_pyz.py --out packages/node-agent/dist/node-agent.pyz

确定性约束（字节可复现）：
- zip 条目按归档内路径排序；
- 固定时间戳 1980-01-01 00:00:00（zip 纪元下界）；
- 固定权限：目录 0755、普通文件 0644、入口 __main__.py 0755；
- 不写入绝对路径、不写 __pycache__/*.pyc、不写构建机用户名或时间；
- 使用 ZIP_STORED（无压缩器差异），因此同一源码树必然得到同一 sha256。

载荷只包含 ghostfleet_agent 包与入口 __main__.py；入口不依赖 cwd、不读环境
变量、不往自己的归档写字节（PYTHONDONTWRITEBYTECODE=1 由 unit 设置）。
"""
from __future__ import annotations

import argparse
import hashlib
import os
import stat
import sys
import zipfile

FIXED_TIMESTAMP = (1980, 1, 1, 0, 0, 0)
DIR_MODE = 0o755
FILE_MODE = 0o644
ENTRY_MODE = 0o755
PACKAGE_NAME = "ghostfleet_agent"

ENTRY_SOURCE = """#!/usr/bin/env python3
# GhostFleet node agent zipapp entry point (generated by tools/build_pyz.py).
import sys

from ghostfleet_agent.cli import main

raise SystemExit(main())
"""


def repo_package_root() -> str:
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _iter_package_files(package_root: str) -> list[tuple[str, str]]:
    source_dir = os.path.join(package_root, "src", PACKAGE_NAME)
    if not os.path.isdir(source_dir):
        raise SystemExit(f"package source directory is missing: {source_dir}")
    entries: list[tuple[str, str]] = []
    for directory, subdirectories, filenames in os.walk(source_dir):
        subdirectories.sort()
        filenames.sort()
        for name in filenames:
            if name.endswith((".pyc", ".pyo")):
                continue
            full = os.path.join(directory, name)
            relative = os.path.relpath(full, os.path.join(package_root, "src"))
            entries.append((relative.replace(os.sep, "/"), full))
    entries.sort(key=lambda item: item[0])
    return entries


def _add_entry(archive: zipfile.ZipFile, name: str, data: bytes, mode: int) -> None:
    info = zipfile.ZipInfo(filename=name, date_time=FIXED_TIMESTAMP)
    info.compress_type = zipfile.ZIP_STORED
    info.create_system = 3  # unix，让 external_attr 的权限位有意义
    info.external_attr = (mode & 0xFFFF) << 16
    archive.writestr(info, data)


def build(output_path: str, package_root: str | None = None) -> str:
    """写出确定性 pyz 并返回其 sha256（十六进制）。"""
    root = package_root or repo_package_root()
    entries = _iter_package_files(root)
    payload: list[tuple[str, bytes, int]] = [("__main__.py", ENTRY_SOURCE.encode("utf-8"), ENTRY_MODE)]
    directories: set[str] = set()
    for archive_name, full_path in entries:
        with open(full_path, "rb") as handle:
            data = handle.read()
        payload.append((archive_name, data, FILE_MODE))
        parts = archive_name.split("/")[:-1]
        for index in range(len(parts)):
            directories.add("/".join(parts[: index + 1]) + "/")
    payload.sort(key=lambda item: item[0])

    output_path = os.path.abspath(output_path)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    temporary = output_path + ".tmp"
    with zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_STORED) as archive:
        for directory in sorted(directories):
            _add_entry(archive, directory, b"", DIR_MODE)
        for name, data, mode in payload:
            _add_entry(archive, name, data, mode)
    with open(temporary, "rb") as handle:
        blob = handle.read()
    digest = hashlib.sha256(blob).hexdigest()
    if hasattr(os, "chmod"):
        os.chmod(temporary, 0o755)
    os.replace(temporary, output_path)
    return digest


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Build the deterministic GhostFleet node-agent zipapp.")
    parser.add_argument("--out", required=True, help="输出 .pyz 路径")
    parser.add_argument("--package-root", default=None, help="包目录（默认由脚本位置推导）")
    arguments = parser.parse_args(argv)
    digest = build(arguments.out, arguments.package_root)
    sys.stdout.write(f"{digest}  {os.path.abspath(arguments.out)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
