async function main() {
  const argv = process.argv.slice(2);
  const command = argv[0];
  if (!command || command === "--help" || command === "-h") {
    process.stderr.write("usage: node " + SCRIPT_PATH + " <" + [...COMMANDS.keys()].join("|") + "> [flags]\n");
    process.exitCode = 2;
    return;
  }
  const implementation = COMMANDS.get(command);
  if (!implementation) fail("AC_UNKNOWN_COMMAND", "unknown subcommand: " + command);
  await implementation(argv.slice(1));
}

main().catch((error) => {
  if (error instanceof AcceptanceError) {
    process.stderr.write(error.code + ": " + error.message + "\n");
    process.exitCode = 4;
    return;
  }
  process.stderr.write("AC_UNEXPECTED: " + (error?.stack ?? String(error)) + "\n");
  process.exitCode = 5;
});